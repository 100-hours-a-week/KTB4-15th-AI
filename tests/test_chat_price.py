"""가격 규칙. 2026-09-30 에 정한 표를 그대로 옮겼다."""

import pytest

from app.chat.price import NO_UPPER_BOUND, parse_price


@pytest.mark.parametrize(
    ("message", "expected"),
    [
        # N만원대 — 끝자리가 0이면 한 자리 위로 올라간다
        ("5만원대 상의 추천해줘", (50_000, 59_999)),
        ("10만원대 셔츠", (100_000, 199_999)),
        ("15만원대 니트", (150_000, 159_999)),
        ("20만원대 아우터", (200_000, 299_999)),
        ("만원대 티셔츠", (10_000, 19_999)),
        # 이하 / 미만
        ("5만원 이하", (0, 50_000)),
        ("5만 원 이내로", (0, 50_000)),
        ("7만원까지", (0, 70_000)),
        ("5만원 아래", (0, 50_000)),
        ("5만원 미만", (0, 49_999)),
        # 이상
        ("5만원 이상", (50_000, NO_UPPER_BOUND)),
        ("100만원 이상", (1_000_000, NO_UPPER_BOUND)),
        ("5만원 넘는 거", (50_000, NO_UPPER_BOUND)),
        ("5만원이 넘는 거", (50_000, NO_UPPER_BOUND)),
        ("5만원 초과", (50_000, NO_UPPER_BOUND)),
        # 범위
        ("5~7만원", (50_000, 70_000)),
        ("5만원~7만원 사이", (50_000, 70_000)),
        ("5만원에서 7만원", (50_000, 70_000)),
        ("5만원부터 7만원까지", (50_000, 70_000)),
        # 정도 (±10%)
        ("5만원 정도", (45_000, 55_000)),
        ("5만원쯤", (45_000, 55_000)),
        ("5만원 내외", (45_000, 55_000)),
        # 숫자 표기
        ("오만원 이하", (0, 50_000)),
        ("십오만원대", (150_000, 159_999)),
        ("삼만오천원 이하", (0, 35_000)),
        ("50000원 이하", (0, 50_000)),
        ("35,000원 이하", (0, 35_000)),
        ("5천원대 양말", (5_000, 5_999)),
        ("오천원 이하", (0, 5_000)),
    ],
)
def test_price_rules(message, expected):
    assert parse_price(message) == expected


@pytest.mark.parametrize(
    "message",
    ["검정 상의 추천해줘", "두 번째 거 얼마야?", "이 옷 오늘 입을래", "백팩 추천", "사이즈 M-L"],
)
def test_no_price(message):
    assert parse_price(message) is None
